function asError(res, result) {
    if (!result || !result.error) return false;
    res.status(result.error.status).json({ code: "BUSINESS_RULE", message: result.error.message });
    return true;
}

export function createV1Routes(env, runtime = {}) {
    const router = Router();
    const authMiddleware = createAuthMiddleware(env.JWT_SECRET);
    const userLock = createUserLockMiddleware({ redisClient: runtime.redisClient, ttlSec: 8 });
    const idempotency = createIdempotencyMiddleware({ redisClient: runtime.redisClient, ttlSec: 300 });

    router.post("/auth/login", async (req, res) => {
        const { provider, idToken, platform, externalId } = req.body || {};
        const requestedProvider = provider || platform || "guest";
        let identity;

        if (requestedProvider === "guest") {
            // Guest identity is generated by the server in production; externalId is dev/test only.
            const isProduction = String(env.NODE_ENV || "development").toLowerCase() === "production";
            identity = {
                provider: "guest",
                providerUid: isProduction ? randomUUID() : (externalId || randomUUID()),
                email: "",
                displayName: ""
            };
        } else {
            try {
                const verified = await verifyFirebaseIdToken(idToken, env.FIREBASE_PROJECT_ID);
                identity = {
                    provider: verified.provider,
                    providerUid: verified.uid,
                    email: verified.email,
                    displayName: verified.displayName
                };
            } catch {
                return res.status(401).json({ code: "UNAUTHENTICATED", message: "A valid Firebase ID token is required" });
            }
        }

        const resolvedProvider = identity.provider;
        const resolvedProviderUid = identity.providerUid;
        const db = await readDb();
        const userId = getUserId(resolvedProvider, resolvedProviderUid);
        const user = ensureUser(db, userId, identity);
        ensureV1State(user);

        const token = createSessionToken({ sub: userId, provider: resolvedProvider, providerUid: resolvedProviderUid }, env.JWT_SECRET);
        await writeDb(db);

        res.json({
            accessToken: token,
            refreshToken: token,
            expiresInSec: 7 * 24 * 3600,
            player: toPlayerProfile(userId, user, 1)
        });
    });

    router.use(authMiddleware);

    router.get("/player/me", async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        res.json(getPlayerMe(req.user.sub, user));
    });

    router.post("/player/sync", async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        const result = syncState(req.user.sub, user, req.body || {});
        await writeDb(db);
        res.json(result);
    });

    router.get("/expeditions/status", async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        res.json(getExpeditionStatus(user));
    });

    router.post("/expeditions/start", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        const result = startExpedition(user, req.body || {});
        if (asError(res, result)) return;
        await writeDb(db);
        res.json(result);
    });

    router.post("/expeditions/claim", userLock, idempotency, async (req, res) => {
        const { expeditionId, idempotencyKey } = req.body || {};
        if (!expeditionId || !idempotencyKey) return res.status(400).json({ code: "BAD_REQUEST", message: "expeditionId and idempotencyKey are required" });
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        const result = claimExpedition(user, { expeditionId });
        if (asError(res, result)) return;
        await writeDb(db);
        res.json(result);
    });

    router.get("/heroes", async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        res.json(listHeroes(user));
    });

    router.post("/heroes/:heroId/level-up", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        const result = levelUpHero(user, req.params.heroId, req.body?.levels || 1);
        if (asError(res, result)) return;

        await writeDb(db);
        res.json(result);
    });

    router.post("/heroes/:heroId/star-up", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        const result = starUpHero(user, req.params.heroId);
        if (asError(res, result)) return;

        await writeDb(db);
        res.json(result);
    });

    router.post("/heroes/:heroId/ascend", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        const result = ascendHero(user, req.params.heroId);
        if (asError(res, result)) return;

        await writeDb(db);
        res.json(result);
    });

    router.get("/buildings", async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        res.json(listBuildings(user));
    });

    router.post("/buildings/start", userLock, async (req, res) => {
        const { buildingType, slotCode, targetLevel } = req.body || {};
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        const result = startBuild(user, buildingType, slotCode, targetLevel);
        if (asError(res, result)) return;

        await writeDb(db);
        res.json(result);
    });

    router.post("/buildings/complete", idempotency, userLock, async (req, res) => {
        const { taskId } = req.body || {};
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        const result = completeBuild(user, taskId);
        if (asError(res, result)) return;

        await writeDb(db);
        res.json(result);
    });

    router.post("/buildings/queue/speed-up", userLock, async (req, res) => {
        const { taskId, gemBudgetLimit } = req.body || {};
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        const result = speedUpBuild(user, taskId, gemBudgetLimit);
        if (asError(res, result)) return;

        await writeDb(db);
        res.json(result);
    });

    router.get("/world/tiles", async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        const x = Number(req.query.x || 0);
        const y = Number(req.query.y || 0);
        const radius = Number(req.query.radius || 6);
        res.json(queryWorldTiles(user, x, y, radius));
    });

    router.post("/world/marches/start", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        const result = startMarch(user, req.body || {});
        await writeDb(db);
        res.json(result);
    });

    router.post("/world/rallies", userLock, async (req, res) => {
        const joinWindowSec = Number(req.body?.joinWindowSec || 300);
        res.json(createRally(req.user.sub, { joinWindowSec }));
    });

    router.post("/alliances", userLock, async (req, res) => {
        const { name, tag, languageCode = "pt-BR" } = req.body || {};
        if (!name || !tag) return res.status(400).json({ code: "BAD_REQUEST", message: "name and tag are required" });

        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        const alliance = createAlliance(db, req.user.sub, { name, tag, languageCode });
        ensureV1State(user);
        user.v1.alliances = { allianceId: alliance.allianceId, name, tag };
        await writeDb(db);

        res.json(alliance);
    });

    router.get("/alliances", async (req, res) => {
        const db = await readDb();
        res.json(searchAlliances(db, req.query.q || ""));
    });

    router.post("/alliances/:allianceId/join", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        const result = joinAlliance(db, user, req.params.allianceId);
        if (asError(res, result)) return;

        await writeDb(db);
        res.json(result);
    });

    router.get("/rankings/power", async (req, res) => {
        const db = await readDb();
        const page = Number(req.query.page || 1);
        const pageSize = Number(req.query.pageSize || 50);
        res.json(getPowerRanking(db, page, pageSize));
    });

    router.post("/shop/purchase", idempotency, userLock, async (req, res) => {
        const { sku, quantity, idempotencyKey } = req.body || {};
        if (!sku || !idempotencyKey) {
            return res.status(400).json({ code: "BAD_REQUEST", message: "sku and idempotencyKey are required" });
        }

        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        const result = shopPurchase(user, { sku, quantity: Number(quantity || 1) });
        if (asError(res, result)) return;

        await writeDb(db);
        res.json(result);
    });

    router.post("/pass/claim", idempotency, userLock, async (req, res) => {
        const { seasonId, tier, premiumTrack } = req.body || {};
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });

        const result = claimBattlePass(user, {
            seasonId: seasonId || "season_1",
            tier: Number(tier || 1),
            premiumTrack: Boolean(premiumTrack)
        });
        if (asError(res, result)) return;

        await writeDb(db);
        res.json(result);
    });


    // Server-authoritative map operations. These records are stored with the player
    // state so they survive service restarts and are not trusted to the browser.
    router.get("/world/battle-history", async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        return res.json(getBattleHistory(user, req.query.limit));
    });

    router.post("/world/hunts/start", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        const result = startHunt(req.user.sub, user, req.body || {});
        if (asError(res, result)) return;
        await writeDb(db);
        return res.json(result);
    });

    router.post("/world/hunts/:operationId/resolve", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        const result = resolveHunt(db, req.user.sub, user, req.params.operationId);
        if (asError(res, result)) return;
        await writeDb(db);
        return res.json(result);
    });

    router.post("/world/alliance-rallies", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        const result = createServerAllianceRally(db, req.user.sub, user, req.body || {});
        if (asError(res, result)) return;
        await writeDb(db);
        return res.json(result.rally ? { ...result, ...result.rally } : result);
    });

    router.get("/world/alliance-rallies/:operationId", async (req, res) => {
        const db = await readDb();
        const result = getAllianceRally(db, req.user.sub, req.params.operationId);
        if (asError(res, result)) return;
        return res.json(result);
    });

    router.post("/world/alliance-rallies/:operationId/join", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        const result = joinAllianceRally(db, req.user.sub, user, { ...(req.body || {}), operationId: req.params.operationId });
        if (asError(res, result)) return;
        await writeDb(db);
        return res.json(result);
    });

    router.post("/world/alliance-rallies/:operationId/close", userLock, async (req, res) => {
        const db = await readDb();
        const result = transitionAllianceRally(db, req.user.sub, "close", req.params.operationId);
        if (asError(res, result)) return;
        await writeDb(db);
        return res.json(result);
    });

    router.post("/world/alliance-rallies/:operationId/dispatch", userLock, async (req, res) => {
        const db = await readDb();
        const result = transitionAllianceRally(db, req.user.sub, "dispatch", req.params.operationId);
        if (asError(res, result)) return;
        await writeDb(db);
        return res.json(result);
    });

    router.post("/world/alliance-rallies/:operationId/resolve", userLock, async (req, res) => {
        const db = await readDb();
        const result = resolveAllianceRally(db, req.user.sub, req.params.operationId);
        if (asError(res, result)) return;
        await writeDb(db);
        return res.json(result);
    });

    router.get("/inventory/chests", async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        return res.json(getServerChests(user));
    });

    router.post("/inventory/chests/:chestId/open", idempotency, userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        const key = String(req.body?.idempotencyKey || req.headers["x-idempotency-key"] || "");
        const result = openServerChest(user, req.params.chestId, key);
        if (asError(res, result)) return;
        await writeDb(db);
        return res.json(result);
    });

    router.get("/vehicle/loadout", async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        return res.json(getVehicleLoadout(user));
    });

    router.post("/vehicle/presets/active", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        const result = setActiveVehiclePreset(user, req.body?.presetId);
        if (asError(res, result)) return;
        await writeDb(db);
        return res.json(result);
    });

    router.post("/vehicle/chips/equip", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        const result = equipVehicleChip(user, req.body || {});
        if (asError(res, result)) return;
        await writeDb(db);
        return res.json(result);
    });

    router.post("/vehicle/chips/remove", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        const result = removeVehicleChip(user, req.body || {});
        if (asError(res, result)) return;
        await writeDb(db);
        return res.json(result);
    });

    router.post("/vehicle/chips/:chipId/upgrade", userLock, async (req, res) => {
        const db = await readDb();
        const user = db.users[req.user.sub];
        if (!user) return res.status(404).json({ code: "NOT_FOUND", message: "User not found" });
        const result = upgradeVehicleChip(user, req.params.chipId);
        if (asError(res, result)) return;
        await writeDb(db);
        return res.json(result);
    });

    return router;
}
