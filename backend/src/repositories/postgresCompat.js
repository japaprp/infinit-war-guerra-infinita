import pg from "pg";

const { Pool } = pg;

const conflictColumns = {
    app_state: "id",
    users: "external_id",
    heroes: "user_id, hero_code",
    buildings: "user_id, slot_code",
    inventory: "external_id, item_code",
    receipts: "receipt_id",
    alliances: "alliance_uid"
};

function translateSql(input) {
    let sql = String(input);
    sql = sql.replace(/ENGINE\s*=\s*InnoDB/gi, "");
    sql = sql.replace(/\bBIGINT\s+UNSIGNED\b/gi, "BIGINT");
    sql = sql.replace(/\bINT\s+UNSIGNED\b/gi, "INTEGER");
    sql = sql.replace(/\bSMALLINT\s+UNSIGNED\b/gi, "SMALLINT");
    sql = sql.replace(/\bTINYINT\s+UNSIGNED\b/gi, "SMALLINT");
    sql = sql.replace(/TINYINT\(1\)/gi, "SMALLINT");
    sql = sql.replace(/\bAUTO_INCREMENT\b/gi, "GENERATED BY DEFAULT AS IDENTITY");
    sql = sql.replace(/\bDATETIME\((\d+)\)/gi, "TIMESTAMP($1)");
    sql = sql.replace(/\bDATETIME\b/gi, "TIMESTAMP");
    sql = sql.replace(/\s+ON UPDATE CURRENT_TIMESTAMP(?:\(\d+\))?/gi, "");
    sql = sql.replace(/UNIQUE KEY\s+(\w+)\s*\(([^)]+)\)/gi, "CONSTRAINT $1 UNIQUE ($2)");
    sql = sql.replace(/,?\s*KEY\s+\w+\s*\([^)]+\)/gi, "");

    sql = sql.replace(/ON DUPLICATE KEY UPDATE([\s\S]*?)(?=;?$)/i, (_match, assignments) => {
        const table = sql.match(/INSERT\s+INTO\s+(\w+)/i)?.[1]?.toLowerCase();
        const target = conflictColumns[table];
        if (!target) throw new Error(`No PostgreSQL conflict target configured for table ${table || "unknown"}`);
        const updates = assignments
            .replace(/\bVALUES\s*\(\s*(\w+)\s*\)/gi, "EXCLUDED.$1")
            .trim()
            .replace(/,$/, "");
        return `ON CONFLICT (${target}) DO UPDATE SET ${updates}`;
    });

    let parameterIndex = 0;
    sql = sql.replace(/\?/g, () => `$${++parameterIndex}`);
    return sql.replace(/;\s*$/, "");
}

function convertDdl(sql) {
    let translated = translateSql(sql);
    translated = translated.replace(/\bJSON\b/gi, "JSONB");
    translated = translated.replace(/\bJSON_OBJECT\([^)]*\)/gi, "'{}'::jsonb");
    return translated;
}

function wrapClient(client) {
    return {
        async query(sql, values = []) {
            const translated = /CREATE\s+TABLE/i.test(String(sql)) ? convertDdl(sql) : translateSql(sql);
            const result = await client.query(translated, values);
            return [result.rows || [], result.fields || []];
        },
        beginTransaction() {
            return client.query("BEGIN");
        },
        commit() {
            return client.query("COMMIT");
        },
        rollback() {
            return client.query("ROLLBACK");
        },
        release() {
            client.release();
        }
    };
}

export function createPostgresPool(config) {
    const pool = new Pool({
        connectionString: config.DATABASE_URL || config.MYSQL_URL || undefined,
        host: config.PG_HOST || config.MYSQL_HOST || undefined,
        port: config.PG_PORT || config.MYSQL_PORT ? Number(config.PG_PORT || config.MYSQL_PORT) : undefined,
        database: config.PG_DATABASE || config.MYSQL_DATABASE || undefined,
        user: config.PG_USER || config.MYSQL_USER || undefined,
        password: config.PG_PASSWORD || config.MYSQL_PASSWORD || undefined,
        ssl: (config.PG_SSL || config.MYSQL_SSL) ? { rejectUnauthorized: true } : undefined,
        max: 8,
        connectionTimeoutMillis: 10000
    });

    return {
        async query(sql, values = []) {
            const translated = /CREATE\s+TABLE/i.test(String(sql)) ? convertDdl(sql) : translateSql(sql);
            const result = await pool.query(translated, values);
            return [result.rows || [], result.fields || []];
        },
        async getConnection() {
            return wrapClient(await pool.connect());
        },
        async end() {
            await pool.end();
        }
    };
}

export default { createPool: createPostgresPool };
