-- PostgreSQL schema for Guerra Infinita (Supabase).
-- Applied to the dedicated guerra-infinita-db project; no Perifa-Pro data is involved.

CREATE TABLE IF NOT EXISTS public.app_state (
  id smallint PRIMARY KEY CHECK (id = 1),
  payload jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id varchar(80) NOT NULL UNIQUE,
  nickname varchar(32) NOT NULL,
  level integer NOT NULL DEFAULT 1 CHECK (level >= 0),
  vip_level smallint NOT NULL DEFAULT 0 CHECK (vip_level >= 0),
  power bigint NOT NULL DEFAULT 0 CHECK (power >= 0),
  realm_id integer NOT NULL DEFAULT 1 CHECK (realm_id >= 0),
  profile_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.heroes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  hero_code varchar(48) NOT NULL,
  rarity varchar(16) NOT NULL,
  level smallint NOT NULL DEFAULT 1 CHECK (level >= 0),
  stars smallint NOT NULL DEFAULT 1 CHECK (stars >= 0),
  ascension smallint NOT NULL DEFAULT 0 CHECK (ascension >= 0),
  shards_owned integer NOT NULL DEFAULT 0 CHECK (shards_owned >= 0),
  stats_json jsonb,
  skill_levels_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_heroes_user_code UNIQUE (user_id, hero_code)
);

CREATE TABLE IF NOT EXISTS public.buildings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  building_type varchar(32) NOT NULL,
  slot_code varchar(32) NOT NULL,
  level smallint NOT NULL DEFAULT 1 CHECK (level >= 0),
  state varchar(16) NOT NULL DEFAULT 'IDLE',
  end_at_ms bigint NOT NULL DEFAULT 0 CHECK (end_at_ms >= 0),
  task_id varchar(80),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_buildings_user_slot UNIQUE (user_id, slot_code)
);

CREATE TABLE IF NOT EXISTS public.inventory (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id varchar(80) NOT NULL,
  item_code varchar(64) NOT NULL,
  quantity bigint NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  metadata_json jsonb,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_inventory_owner_item UNIQUE (external_id, item_code)
);

CREATE TABLE IF NOT EXISTS public.receipts (
  receipt_id varchar(64) PRIMARY KEY,
  external_id varchar(80) NOT NULL,
  hero_id varchar(64) NOT NULL,
  pack_id varchar(64) NOT NULL,
  cost_gems integer NOT NULL CHECK (cost_gems >= 0),
  issued_at_ms bigint NOT NULL CHECK (issued_at_ms >= 0),
  signature varchar(128) NOT NULL,
  used smallint NOT NULL DEFAULT 0 CHECK (used IN (0,1)),
  used_at_ms bigint,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_receipts_external ON public.receipts (external_id);

CREATE TABLE IF NOT EXISTS public.alliances (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alliance_uid varchar(80) NOT NULL UNIQUE,
  realm_id integer NOT NULL DEFAULT 1 CHECK (realm_id >= 0),
  name varchar(32) NOT NULL,
  tag varchar(8) NOT NULL,
  leader_external_id varchar(80) NOT NULL,
  member_count integer NOT NULL DEFAULT 1 CHECK (member_count >= 0),
  power bigint NOT NULL DEFAULT 0 CHECK (power >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.battles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  realm_id integer NOT NULL DEFAULT 1,
  attacker_external_id varchar(80) NOT NULL,
  defender_external_id varchar(80) NOT NULL,
  battle_type varchar(16) NOT NULL,
  result varchar(16) NOT NULL,
  report_json jsonb,
  ended_at timestamptz NOT NULL DEFAULT now()
);

