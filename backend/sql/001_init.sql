-- PostgreSQL schema for Supabase / PostgreSQL deployments.
-- Connect to the target database before applying this file; database creation is managed externally.

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id VARCHAR(80) NOT NULL UNIQUE,
  nickname VARCHAR(32) NOT NULL,
  level INTEGER NOT NULL DEFAULT 1,
  vip_level SMALLINT NOT NULL DEFAULT 0,
  power BIGINT NOT NULL DEFAULT 0,
  realm_id INTEGER NOT NULL DEFAULT 1,
  profile_json JSONB,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);

CREATE TABLE IF NOT EXISTS heroes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  hero_code VARCHAR(48) NOT NULL,
  rarity VARCHAR(16) NOT NULL,
  level SMALLINT NOT NULL DEFAULT 1,
  stars SMALLINT NOT NULL DEFAULT 1,
  ascension SMALLINT NOT NULL DEFAULT 0,
  shards_owned INTEGER NOT NULL DEFAULT 0,
  stats_json JSONB,
  skill_levels_json JSONB,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT uk_heroes_user_code UNIQUE (user_id, hero_code)
);

CREATE TABLE IF NOT EXISTS buildings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  building_type VARCHAR(32) NOT NULL,
  slot_code VARCHAR(32) NOT NULL,
  level SMALLINT NOT NULL DEFAULT 1,
  state VARCHAR(16) NOT NULL DEFAULT 'IDLE',
  end_at_ms BIGINT NOT NULL DEFAULT 0,
  task_id VARCHAR(80),
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT uk_buildings_user_slot UNIQUE (user_id, slot_code)
);

CREATE TABLE IF NOT EXISTS alliances (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alliance_uid VARCHAR(80) NOT NULL UNIQUE,
  realm_id INTEGER NOT NULL DEFAULT 1,
  name VARCHAR(32) NOT NULL,
  tag VARCHAR(8) NOT NULL,
  leader_external_id VARCHAR(80) NOT NULL,
  member_count INTEGER NOT NULL DEFAULT 1,
  power BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);

CREATE TABLE IF NOT EXISTS battles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  realm_id INTEGER NOT NULL DEFAULT 1,
  attacker_external_id VARCHAR(80) NOT NULL,
  defender_external_id VARCHAR(80) NOT NULL,
  battle_type VARCHAR(16) NOT NULL,
  result VARCHAR(16) NOT NULL,
  report_json JSONB,
  ended_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);

CREATE TABLE IF NOT EXISTS inventory (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id VARCHAR(80) NOT NULL,
  item_code VARCHAR(64) NOT NULL,
  quantity BIGINT NOT NULL DEFAULT 0,
  metadata_json JSONB,
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT uk_inventory_owner_item UNIQUE (external_id, item_code)
);

CREATE TABLE IF NOT EXISTS receipts (
  receipt_id VARCHAR(64) PRIMARY KEY,
  external_id VARCHAR(80) NOT NULL,
  hero_id VARCHAR(64) NOT NULL,
  pack_id VARCHAR(64) NOT NULL,
  cost_gems INTEGER NOT NULL,
  issued_at_ms BIGINT NOT NULL,
  signature VARCHAR(128) NOT NULL,
  used SMALLINT NOT NULL DEFAULT 0,
  used_at_ms BIGINT,
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE INDEX IF NOT EXISTS idx_receipts_external ON receipts (external_id);

CREATE TABLE IF NOT EXISTS app_state (
  id SMALLINT PRIMARY KEY,
  payload JSONB NOT NULL,
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);

INSERT INTO app_state (id, payload)
VALUES (1, '{"users":{},"receipts":{},"alliances":{}}'::jsonb)
ON CONFLICT (id) DO NOTHING;
